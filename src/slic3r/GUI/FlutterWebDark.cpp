struct Rgb { int r, g, b; };

// Exact light -> dark pairs from StateColor.cpp (gDarkColors).
const std::map<uint32_t, uint32_t> &prepare_dark()
{
    static const std::map<uint32_t, uint32_t> table = {
        {0x009688, 0x00675B}, {0x1F8EEA, 0x2778D2}, {0xFF6F00, 0xD15B00}, {0xD01B1B, 0xBB2A3A},
        {0x262E30, 0xEFEFF0}, {0xDFDFDF, 0x3E3E45}, {0xD4D4D4, 0x4D4D54}, {0x6B6A6A, 0x909090},
        {0x6B6B6A, 0xB3B3B5}, {0x2C2C2E, 0xB3B3B4}, {0x6B6B6B, 0x818183}, {0xACACAC, 0x65656A},
        {0xEEEEEE, 0x4C4C55}, {0xE8E8E8, 0x3E3E45}, {0x323A3D, 0xE5E5E4}, {0xFFFFFF, 0x2D2D31},
        {0xF8F8F8, 0x36363C}, {0xF1F1F1, 0x36363B}, {0x3B4446, 0x2D2D30}, {0xCECECE, 0x54545B},
        {0x000000, 0xFFFFFE}, {0xF4F4F4, 0x36363D}, {0xDBDBDB, 0x4A4A51}, {0x323A3C, 0xE5E5E6},
        {0x303A3C, 0xE5E5E5}, {0xFEFFFF, 0x242428}, {0x363636, 0xB2B3B5}, {0xF0F0F1, 0x333337},
        {0x9E9E9E, 0x53545A}, {0xD9D9D9, 0x2D2D32}, {0xBFE1DE, 0x223C3C}, {0xE5F0EE, 0x283232},
        {0xF8F7F7, 0x2A2A2E}, {0xF0F0F0, 0x3F3F46}, {0xF3F4F6, 0x3A3A3F}, {0x242424, 0xE4E4E7},
    };
    return table;
}

// Lightness curve for neutral greys, fitted to the background/text pairs above.
// Keep in sync with NEUTRAL_CURVE in scripts/flutter_web_dark.py.
double neutral_curve(double v)
{
    static const std::array<std::pair<double, double>, 12> curve = {{
        {0, 255}, {36, 228}, {54, 190}, {107, 135}, {128, 120}, {158, 106},
        {172, 100}, {200, 86}, {220, 72}, {235, 62}, {245, 54}, {255, 45},
    }};
    for (size_t i = 1; i < curve.size(); ++i)
        if (v <= curve[i].first)
            return curve[i - 1].second + (curve[i].second - curve[i - 1].second) * (v - curve[i - 1].first) /
                                             (curve[i].first - curve[i - 1].first);
    return curve.back().second;
}

double hue_to_rgb(double m1, double m2, double h)
{
    h = h - std::floor(h);
    if (h < 1.0 / 6) return m1 + (m2 - m1) * h * 6;
    if (h < 0.5) return m2;
    if (h < 2.0 / 3) return m1 + (m2 - m1) * (2.0 / 3 - h) * 6;
    return m1;
}

// Map a light-theme color to its dark counterpart; `alpha` may be adjusted.
Rgb map_rgb(Rgb c, double &alpha)
{
    const int    mx = std::max({c.r, c.g, c.b}), mn = std::min({c.r, c.g, c.b});
    const uint32_t key = (uint32_t(c.r) << 16) | (uint32_t(c.g) << 8) | uint32_t(c.b);
    Rgb out;
    auto it = prepare_dark().find(key);
    if (it != prepare_dark().end()) {
        out = {int(it->second >> 16), int((it->second >> 8) & 255), int(it->second & 255)};
    } else if (mx - mn <= 24) {
        // Neutral: remap lightness, keep the faint blue tint of the Prepare greys.
        const int v = int(std::lround(neutral_curve(0.299 * c.r + 0.587 * c.g + 0.114 * c.b)));
        out = {v, v, std::min(255, v + (v < 128 ? 4 : 1))};
    } else {
        // HLS, as Python's colorsys.
        const double r = c.r / 255.0, g = c.g / 255.0, b = c.b / 255.0;
        const double maxc = mx / 255.0, minc = mn / 255.0, sumc = maxc + minc, rangec = maxc - minc;
        double l = sumc / 2.0;
        double s = l <= 0.5 ? rangec / sumc : rangec / (2.0 - sumc);
        const double rc = (maxc - r) / rangec, gc = (maxc - g) / rangec, bc = (maxc - b) / rangec;
        double h = r == maxc ? bc - gc : g == maxc ? 2.0 + rc - bc : 4.0 + gc - rc;
        h = h / 6.0 - std::floor(h / 6.0);
        if (l >= 0.85) {        // pastel backgrounds / chips
            l = 0.20 + (1 - l) * 0.5;
            s = std::min(s, 0.35);
        } else if (l <= 0.20) { // near-black tinted text
            l = 0.85;
        } else {                // accents: darken slightly, like the Prepare palette
            l *= 0.88;
        }
        const double m2 = l <= 0.5 ? l * (1.0 + s) : l + s - l * s, m1 = 2.0 * l - m2;
        out = {int(std::lround(hue_to_rgb(m1, m2, h + 1.0 / 3) * 255)), int(std::lround(hue_to_rgb(m1, m2, h) * 255)),
               int(std::lround(hue_to_rgb(m1, m2, h - 1.0 / 3) * 255))};
    }
    // Translucent black is used for shadows/scrims and dividers: keep it subtle.
    if (key == 0 && alpha < 1.0)
        alpha *= 0.6;
    return out;
}

std::string fmt(double x)
{
    char buf[32];
    std::snprintf(buf, sizeof(buf), "%.12g", x);
    return buf;
}

bool is_ident(char c) { return std::isalnum(static_cast<unsigned char>(c)) || c == '_' || c == '$'; }

// Parse a JS number literal at s[pos]; returns the end position or npos.
size_t parse_number(const std::string &s, size_t pos, double &value)
{
    size_t end = pos;
    while (end < s.size() && (std::isdigit(static_cast<unsigned char>(s[end])) || s[end] == '.' || s[end] == 'e' ||
                              (s[end] == '-' && end > pos && s[end - 1] == 'e')))
        ++end;
    if (end == pos)
        return std::string::npos;
    value = std::strtod(s.substr(pos, end - pos).c_str(), nullptr);
    return end;
}

// A Color constant as emitted by dart2js: new A.<cls>(a,r,g,b,B.<space>) with all
// components in 0..1. Returns the end position or npos.
size_t parse_color(const std::string &s, size_t pos, std::string &cls, std::array<double, 4> &v, std::string &space)
{
    static const std::string prefix = "new A.";
    if (s.compare(pos, prefix.size(), prefix) != 0)
        return std::string::npos;
    size_t p = pos + prefix.size(), q = p;
    while (q < s.size() && is_ident(s[q])) ++q;
    if (q == p || q >= s.size() || s[q] != '(')
        return std::string::npos;
    cls = s.substr(p, q - p);
    p = q + 1;
    for (int i = 0; i < 4; ++i) {
        p = parse_number(s, p, v[i]);
        if (p == std::string::npos || p >= s.size() || s[p] != ',' || v[i] < 0 || v[i] > 1)
            return std::string::npos;
        ++p;
    }
    if (s.compare(p, 2, "B.") != 0)
        return std::string::npos;
    q = p + 2;
    while (q < s.size() && is_ident(s[q])) ++q;
    if (q >= s.size() || s[q] != ')')
        return std::string::npos;
    space = s.substr(p, q - p);
    return q + 1;
}

void replace_all(std::string &s, const std::string &from, const std::string &to)
{
    for (size_t pos = s.find(from); pos != std::string::npos; pos = s.find(from, pos + to.size()))
        s.replace(pos, from.size(), to);
}

uint32_t crc32(const std::string &data)
{
    static const std::array<uint32_t, 256> table = [] {
        std::array<uint32_t, 256> t{};
        for (uint32_t i = 0; i < 256; ++i) {
            uint32_t c = i;
            for (int k = 0; k < 8; ++k)
                c = (c & 1) ? 0xEDB88320u ^ (c >> 1) : c >> 1;
            t[i] = c;
        }
        return t;
    }();
    uint32_t c = 0xFFFFFFFFu;
    for (unsigned char ch : data)
        c = table[(c ^ ch) & 0xFF] ^ (c >> 8);
    return c ^ 0xFFFFFFFFu;
}

bool read_file(const std::string &path, std::string &out)
{
    boost::nowide::ifstream f(path, std::ios::binary);
    if (!f)
        return false;
    std::ostringstream ss;
    ss << f.rdbuf();
    out = ss.str();
    return true;
}

// Prebuilt dark image for `rel` if it exists and was generated from the current source.
std::string prebuilt_image(const std::string &rel, const std::string &source_path)
{
    const std::string dir = resources_dir() + "/web/flutter_web_dark/";
    std::string manifest, source;
    if (!read_file(dir + "manifest.txt", manifest) || !read_file(source_path, source))
        return "";
    char line[16];
    std::snprintf(line, sizeof(line), "%08x ", crc32(source));
    if (manifest.find(std::string(line) + rel + "\n") == std::string::npos) {
        BOOST_LOG_TRIVIAL(info) << "FlutterWebDark: " << rel << " changed, keeping the light image";
        return "";
    }
    return dir + rel;
}

